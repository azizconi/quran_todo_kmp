/**
 * Strings of the reading plan (khatm) and of Ramadan (task F5b) in the five app languages: the card of the home screen, the plan
 * screen and the Ramadan card. Texts with numbers are patterns with `{name}` placeholders, so each language keeps its own word order;
 * days, minutes and pages are counted by [PlanCopy] (`daysLabel`, `pagesLabel`).
 */
@Immutable
