    val screenTitle: String,
    val newPlanTitle: String,
    val newPlanBody: String,
    val presetPattern: String,
    val toDate: String,
    val startTitle: String,
    val fromFirstPage: String,
    val fromCurrentPattern: String,
    val summaryPattern: String,
    val dailyPattern: String,
    val daysLeftPattern: String,
    val lastDay: String,
    val overdueTitle: String,
    val newTarget: String,
    val changeTarget: String,
    val deletePlan: String,
    val deleteTitle: String,
    val deleteBody: String,
    val delete: String,
    val cancel: String,
    val markUpToTitle: String,
    val markUpToHint: String,
    val markUpToAction: String,
    val pageLabel: String,
    val calendarTitle: String,
    val legendRead: String,
    val legendMissed: String,
    val legendToday: String,
    val completeBanner: String,
    val startNew: String,
    val back: String,
    val createdToast: String,
    val deletedToast: String,

    // Ramadan
    val ramadanTitle: String,
    val ramadanUpcomingPattern: String,
    val ramadanNightPattern: String,
    val monthPlan: String,
    val monthPlanHint: String,
    val monthPlanCreatedToast: String,
    val juzTitlePattern: String,
    val listenJuz: String,
    val readJuz: String,
    val juzUnavailable: String,
) {
    private fun String.fill(vararg values: Pair<String, Any>): String =
        values.fold(this) { text, (key, value) -> text.replace("{$key}", value.toString()) }

    private val plan: PlanCopy get() = planCopy(language)

    /** "pages 121–140" (one page: "page 121"). */
    fun pages(first: Int, last: Int): String =
        if (first == last) pageOnePattern.fill("a" to first) else pagesRangePattern.fill("a" to first, "b" to last)

    fun minutes(n: Int): String = minutesPattern.fill("n" to n)

    /** "Khatm: today pages 121–140 · ~25 min". */
    fun cardPending(first: Int, last: Int, minutes: Int): String =
        cardPendingPattern.fill("pages" to pages(first, last), "minutes" to minutes(minutes))

    /** "Khatm: read today · tomorrow pages 141–160". */
    fun cardDone(first: Int, last: Int): String = cardDonePattern.fill("pages" to pages(first, last))

    fun progress(read: Int, total: Int): String = progressPattern.fill("read" to read, "total" to total)

    fun behind(pages: Int): String = behindPattern.fill("pages" to plan.pagesLabel(pages.toFloat()))

    fun ahead(pages: Int): String = aheadPattern.fill("pages" to plan.pagesLabel(pages.toFloat()))

    fun preset(days: Int): String = presetPattern.fill("days" to plan.daysLabel(days))

    fun fromCurrent(page: Int): String = fromCurrentPattern.fill("page" to page)

    /** "604 pages · until 14 March". */
    fun summary(totalPages: Int, untilDate: String): String =
        summaryPattern.fill("pages" to plan.pagesLabel(totalPages.toFloat()), "date" to untilDate)

    fun daily(pages: Int): String = dailyPattern.fill("pages" to plan.pagesLabel(pages.toFloat()))

    fun daysLeft(days: Int): String = daysLeftPattern.fill("days" to plan.daysLabel(days))

    fun ramadanUpcoming(days: Int): String = ramadanUpcomingPattern.fill("days" to plan.daysLabel(days))

    fun ramadanNight(night: Int, daysLeft: Int): String =
        ramadanNightPattern.fill("n" to night, "days" to plan.daysLabel(daysLeft))

    fun juzTitle(juz: Int): String = juzTitlePattern.fill("n" to juz)

    fun dateLabel(epochDay: Int, today: Int): String = plan.dateLabel(epochDay, today)
}

