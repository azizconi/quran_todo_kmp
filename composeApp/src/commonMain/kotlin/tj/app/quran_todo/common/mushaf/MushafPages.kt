    fun isPage(page: Int): Boolean = page in 1..COUNT

    /** True for a surah/ayah pair that exists. */
    fun isAyah(surah: Int, ayah: Int): Boolean = surah in 1..QuranFacts.SURAH_COUNT && ayah in 1..QuranFacts.ayahCount(surah)

    /** The page [surah]:[ayah] starts on, and so the page it is on (an ayah never crosses a page). */
    fun pageOf(surah: Int, ayah: Int): Int {
        val number = QuranFacts.firstAyahNumber(surah) + ayah.coerceAtLeast(1) - 1
        var low = 0
        var high = COUNT - 1
        while (low < high) {
            val middle = (low + high + 1) ushr 1
            if (firstAyahNumber[middle] <= number) low = middle else high = middle - 1
        }
        return low + 1
    }

    /** The first ayah that starts on [page] (1..604). */
    fun firstAyahOf(page: Int): AyahKey {
        val number = firstAyahNumber[page.coerceIn(1, COUNT) - 1]
        var surah = 1
        while (surah < QuranFacts.SURAH_COUNT && QuranFacts.firstAyahNumber(surah + 1) <= number) surah++
        return AyahKey(surah, number - QuranFacts.firstAyahNumber(surah) + 1)
    }

    /** The juz (1..30) of [page]. */
    fun juzOf(page: Int): Int {
        val p = page.coerceIn(1, COUNT)
        var juz = 30
        while (juz > 1 && juzFirstPages[juz - 1] > p) juz--
        return juz
    }

    /** The pages of [juz] (1..30). */
    fun pagesOfJuz(juz: Int): IntRange {
        require(juz in 1..30) { "juz $juz" }
        val first = juzFirstPages[juz - 1]
        val last = if (juz == 30) COUNT else juzFirstPages[juz] - 1
        return first..last
    }

    /** The quarter of a hizb (1..240) at the top of [page]. */
    fun hizbQuarterOf(page: Int): Int = firstHizbQuarter[page.coerceIn(1, COUNT) - 1]

    /** The hizb (1..60) at the top of [page]. */
    fun hizbOf(page: Int): Int = (hizbQuarterOf(page) - 1) / 4 + 1
}
