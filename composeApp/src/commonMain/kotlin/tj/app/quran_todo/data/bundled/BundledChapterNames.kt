package tj.app.quran_todo.data.bundled

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import qurantodo.composeapp.generated.resources.Res
import tj.app.quran_todo.common.i18n.AppLanguage
import tj.app.quran_todo.domain.model.ChapterNameModel

/**
 * Surah names for the languages quran.com has no localized names for (`language=tg` and `language=uz` both
 * answer in English): `files/quran/chapter_names_tg.json` (Cyrillic) and `chapter_names_uz.json` (Latin).
 * They are generated by `scripts/build_chapter_names.py`; the full list for a native speaker to check is
 * `docs/redesign/review/chapter-names-tg-uz.md`. No network is involved.
 */
class BundledChapterNames(
    private val readBytes: suspend (String) -> ByteArray = { path -> Res.readBytes(path) },
) {
    private val mutex = Mutex()
    private val cache = HashMap<AppLanguage, Map<Int, ChapterNameModel>>()

    fun isBundled(language: AppLanguage): Boolean = language == AppLanguage.TG || language == AppLanguage.UZ

    /** The names of [language] by surah number; throws when the file is missing or damaged. */
    suspend fun get(language: AppLanguage): Map<Int, ChapterNameModel> = mutex.withLock {
        cache[language]?.let { return@withLock it }
        val names = withContext(Dispatchers.Default) {
            parse(readBytes(pathFor(language)).decodeToString())
        }
        cache[language] = names
        names
    }

    @Serializable
    private class FileModel(val chapters: List<Row>)

    @Serializable
    private class Row(
        val number: Int,
        val arabic: String,
        val transliteration: String,
        val translated: String,
    )

    companion object {
        fun pathFor(language: AppLanguage): String = when (language) {
            AppLanguage.TG -> "files/quran/chapter_names_tg.json"
            AppLanguage.UZ -> "files/quran/chapter_names_uz.json"
            else -> throw IllegalArgumentException("no bundled chapter names for $language")
        }

        private val json = Json { ignoreUnknownKeys = true }

        /** Parses a bundled file and checks that it names all 114 surahs. */
        fun parse(text: String): Map<Int, ChapterNameModel> {
            val file = json.decodeFromString(FileModel.serializer(), text)
            val names = file.chapters.associate { row ->
                row.number to ChapterNameModel(
                    arabic = row.arabic,
                    transliteration = row.transliteration,
                    translated = row.translated,
                )
            }
            if (names.size != QuranFacts.SURAH_COUNT || (1..QuranFacts.SURAH_COUNT).any { it !in names }) {
                throw QuranDataException("chapter names file does not cover surahs 1..114")
            }
            return names
        }
    }
}
