#!/usr/bin/env python3
"""Builds the bundled Quran text asset used for the first (offline) start of the app.

Source: https://api.alquran.cloud/v1/quran/quran-uthmani - the very same text the app used to download.
Output: composeApp/src/commonMain/composeResources/files/quran/quran-uthmani.tsv

Usage:
    python3 scripts/build_quran_asset.py                 # download and write the asset
    python3 scripts/build_quran_asset.py --input q.json  # use an already downloaded response
    python3 scripts/build_quran_asset.py --check         # only verify the committed asset

Only the standard library is used.

File format (UTF-8, LF line endings, no BOM). Fields are separated by a single TAB; no field can contain
a TAB or a line break (the script checks it). Lines starting with '#' and empty lines are comments.

    E <identifier> <englishName> <format> <language> <name> <type>
        one edition row (what `editions` stores)
    S <number> <name> <englishName> <englishNameTranslation> <revelationType>
        114 surah rows, in order of `number`
    A <number> <surah> <numberInSurah> <juz> <hizbQuarter> <manzil> <page> <ruku>
      <sajdaId> <sajdaRecommended> <sajdaObligatory> <text>
        6236 ayah rows, in order of the global `number` (1..6236). <surah> is the surah number.
        The three sajda columns are empty for ayahs without a prostration; otherwise <sajdaId> is the
        1-based prostration number and the other two are 1 or 0. <text> is the last column.

Cleaning applied while generating:
  * the byte order mark U+FEFF is removed (the API puts it in front of 1:1);
  * nothing else is touched: in particular the Bismillah stays in the first ayah of every surah that has it
    (the old iOS interface shows it straight from the ayah text; Android splits it off itself,
    see ui/reader/Bismillah.kt), and nothing is trimmed or normalized.
"""

import argparse
import json
import os
import sys
import urllib.request

API_URL = "https://api.alquran.cloud/v1/quran/quran-uthmani"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(
    ROOT, "composeApp", "src", "commonMain", "composeResources", "files", "quran", "quran-uthmani.tsv"
)
BOM = chr(0xFEFF)  # byte order mark
SURAH_COUNT = 114
AYAH_COUNT = 6236
SAJDA_COUNT = 15


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "quran-hifz-asset-builder"})
    with urllib.request.urlopen(request, timeout=120) as response:
        return json.loads(response.read().decode("utf-8"))


def field(value):
    text = str(value)
    if "\t" in text or "\n" in text or "\r" in text:
        raise ValueError("field contains a TAB or a line break: %r" % text)
    return text


def build_rows(payload):
    if payload.get("code") != 200:
        raise ValueError("unexpected response: %s" % payload.get("status"))
    data = payload["data"]
    edition = data["edition"]
    surahs = data["surahs"]

    rows = [
        "# Quran text for Quran Hifz: edition quran-uthmani from api.alquran.cloud.",
        "# Generated by scripts/build_quran_asset.py, do not edit by hand. Format: see that script.",
        "\t".join(
            field(v)
            for v in (
                "E",
                edition["identifier"],
                edition["englishName"],
                edition["format"],
                edition["language"],
                edition["name"],
                edition["type"],
            )
        ),
    ]
    for surah in surahs:
        rows.append(
            "\t".join(
                field(v)
                for v in (
                    "S",
                    surah["number"],
                    surah["name"],
                    surah["englishName"],
                    surah["englishNameTranslation"],
                    surah["revelationType"],
                )
            )
        )
    for surah in surahs:
        for ayah in surah["ayahs"]:
            sajda = ayah["sajda"]
            if isinstance(sajda, dict):
                sajda_cols = (
                    sajda["id"],
                    1 if sajda.get("recommended") else 0,
                    1 if sajda.get("obligatory") else 0,
                )
            else:
                sajda_cols = ("", "", "")
            text = ayah["text"].replace(BOM, "")
            rows.append(
                "\t".join(
                    field(v)
                    for v in (
                        "A",
                        ayah["number"],
                        surah["number"],
                        ayah["numberInSurah"],
                        ayah["juz"],
                        ayah["hizbQuarter"],
                        ayah["manzil"],
                        ayah["page"],
                        ayah["ruku"],
                        *sajda_cols,
                        text,
                    )
                )
            )
    return rows


def check(text):
    """Verifies the generated file the same way the app does when it loads it."""
    lines = text.split("\n")
    assert lines[-1] == "", "the file must end with a line break"
    assert BOM not in text, "the file contains U+FEFF"
    surahs = [l for l in lines if l.startswith("S\t")]
    ayahs = [l.split("\t") for l in lines if l.startswith("A\t")]
    assert len(surahs) == SURAH_COUNT, "surahs: %d" % len(surahs)
    assert len(ayahs) == AYAH_COUNT, "ayahs: %d" % len(ayahs)
    assert [int(a[1]) for a in ayahs] == list(range(1, AYAH_COUNT + 1)), "ayah numbers are not 1..6236"
    sajdas = [a for a in ayahs if a[9] != ""]
    assert len(sajdas) == SAJDA_COUNT, "sajdas: %d" % len(sajdas)
    assert all(len(a) == 13 for a in ayahs), "an ayah row does not have 13 columns"
    first = ayahs[0]
    assert (first[2], first[3]) == ("1", "1") and first[12].startswith("بِسْمِ"), (
        "1:1 does not start with the Bismillah"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--input", help="a saved response of %s" % API_URL)
    parser.add_argument("--output", default=OUTPUT)
    parser.add_argument("--check", action="store_true", help="only verify the committed asset")
    args = parser.parse_args()

    if args.check:
        with open(args.output, encoding="utf-8", newline="") as handle:
            check(handle.read())
        print("OK: %s" % args.output)
        return 0

    if args.input:
        with open(args.input, encoding="utf-8") as handle:
            payload = json.load(handle)
    else:
        payload = fetch(API_URL)
    text = "\n".join(build_rows(payload)) + "\n"
    check(text)
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("wrote %s (%d bytes, %d lines)" % (args.output, len(text.encode("utf-8")), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
